
import { StorageItem, ItemEffect, AmpmAisle, SoftStat } from '../types';

/**
 * The AM/PM master catalogue.
 * =========================================================================
 * This file is the item *master data*: `BUY_STORAGE_ITEM` looks an item up
 * here by id and copies it into the player's storage, and the outcome engine
 * resolves authored `inventoryChange` rewards against it too. Anything sold in
 * `data/ampmItems.ts` must therefore exist here under the same id, or the buy
 * silently fails with "Item not available."
 *
 * The shelves are modelled on a real convenience store — dairy, bakery, drinks,
 * snacks, pantry, frozen, household, personal care — because a believable
 * inventory is what lets the *effects* be deranged. Nobody questions a tub of
 * cottage cheese. They question what it did to them.
 *
 * Conventions, so a future reader isn't guessing:
 *
 *  - `effects[]` is the ONLY thing the reducer reads today (`USE_STORAGE_ITEM`).
 *    Guaranteed health/energy therefore lives there, as `chance: 1.0`.
 *  - `deltas` carries the stats `ItemEffect` cannot express — mood, focus,
 *    cleanliness — plus health/energy for items that have no `stat_change`
 *    effect at all. An item never declares the same stat in both places, so
 *    whichever system reads them can't double-count.
 *  - `digestiveRisk` is the chance this ends in a bathroom emergency. Chocolate
 *    milk in a bag is the ceiling (0.35). Everything else is measured against it.
 *  - `gas` feeds the hidden gas meter. Legumes, dairy and carbonation only.
 *  - `uselessness` exists so a joke item reads as a joke rather than a bug. If
 *    an item does nothing, say so on the card and take the credit.
 *  - Items with no `effects` array at all report "has no effect" when used.
 *    That is sometimes the correct outcome and is used deliberately.
 */

// --- authoring shorthand -------------------------------------------------
// `stats` is five numbers and spelling all five out a hundred times buries the
// writing. Order is the same as the interface: power, energy, freshness, risk,
// wackiness.
const st = (power: number, energy: number, freshness: number, risk: number, wackiness: number) =>
    ({ power, energy, freshness, risk, wackiness });

/** A line of text. The default is "this always happens". */
const say = (message: string, chance = 1.0): ItemEffect =>
    ({ type: 'notification', payload: { message }, chance });

/** Health or energy. The reducer clamps, so overshooting is fine. */
const gain = (stat: 'health' | 'energy', value: number, chance = 1.0): ItemEffect =>
    ({ type: 'stat_change', payload: { stat, value }, chance });

/** One of the four status ids the reducer knows how to afflict you with. */
const afflict = (
    statusId: 'diarrhea' | 'gassy' | 'well-fed' | 'energized',
    durationHrs: number,
    description: string,
    chance: number,
): ItemEffect => ({ type: 'status_effect', payload: { statusId, durationHrs, description }, chance });

const soft = (d: Partial<Record<SoftStat, number>>) => d;

