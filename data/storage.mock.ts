/**
 * Alias for readers who correctly object to importing something called a
 * "mock" as production master data. `storageMock` keeps its name because the
 * reducer and the outcome engine import it by that name.
 */
export const STORAGE_CATALOGUE: StorageItem[] = storageMock;

const BY_ID = new Map(storageMock.map(i => [i.id, i]));

/** Master lookup. Returns the shelf copy — clone it before handing it to a player. */
export const getStorageItem = (id: string): StorageItem | undefined => BY_ID.get(id);

/** Everything on one shelf, for shop tabs and the shelf-specials picker. */
export const itemsInAisle = (aisle: AmpmAisle): StorageItem[] =>
    storageMock.filter(i => i.aisle === aisle);

/** Ids of every item the store can actually put in your hands, for sanity checks. */
export const ALL_ITEM_IDS: string[] = storageMock.map(i => i.id);

