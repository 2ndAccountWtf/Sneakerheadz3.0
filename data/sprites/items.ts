import type { SpriteDef } from '../../systems/sprites/types';

/**
 * AM/PM item sprites.
 * ========================================================================
 * Items are authored **16 wide x 16 tall** — square, because these are objects
 * rather than people, and because a square frame can be rotated 90 degrees
 * without changing size. That is what gives the thrown weapons their spin: the
 * chancla's four frames are literally one drawing turned four ways, which is
 * both cheaper and more convincing than four hand-drawn tumbles.
 *
 * The exception is anything radially symmetric. A disc rotated 180 degrees is
 * the same disc, so the frisbee is hand-drawn as wide -> tilted -> edge-on
 * instead. (The preview harness flags frames identical to frame 0 for exactly
 * this reason.)
 *
 * Coverage strategy: the store stocks 102 items and several of them are the
 * same object with a different label — three tubs of ice cream, six canned
 * drinks, ten bagged snacks. Those share a sprite through ITEM_SPRITE_FOR.
 * Weapons never share: each one has to be identifiable mid-air.
 *
 * Palette chars are documented in systems/sprites/palette.ts.
 */

